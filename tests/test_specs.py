@pytest.fixture
def client(config):
    app = create_app(config)
    app.testing = True
    return sign_in(app)


def text_of(pdf: bytes) -> list[str]:
    with pymupdf.open(stream=pdf, filetype="pdf") as doc:
        return [p.get_text() for p in doc]


def test_document_contents(repo, config):
    pages = text_of(specs.build(repo.conn, config))
    body = "\n".join(pages)
    for expected in ["System and Technical Specifications", "MICRONET SOFTWARE MANILA, INC.",
                     "002-372-466-00000", "1. General information", "Software used",
                     "2. Database architecture", "journal_entries", "audit_log",
                     "3. System functions and features", "4. Process and data flows",
                     "Overall data flow", "Service Invoice life cycle", "Automatic postings",
                     "5. Controls and data security", "6. Backup procedures and disaster recovery",
                     "Restoring a backup", "7. Reports generated by the system",
                     "Summary List of Sales", "8. Certification", "Signature over printed name"]:
        assert expected in body, expected
    assert f"Page 1 of {len(pages)}" in pages[0]
    annex = [p for p in pages if "FACSIMILE, SAMPLE DATA" in p]
    labels = {line.split(" ")[1] for p in annex for line in p.splitlines() if line.startswith("ANNEX ")}
    assert {"A-1", "A-2", "A-3", "B-1", "B-5", "B-6", "C-1", "C-4", "D-1"} <= labels
    assert any("SERVICE INVOICE" in p and "Less: Withholding Tax" in p for p in annex)
    assert any("Sales Journal" in p for p in annex)
    assert any("VOID" in p for p in annex)


def test_company_records_stay_out(repo, config):
    repo.issue(make_invoice(buyer_name="REAL CLIENT OF MICRONET"))
    before = repo.conn.execute("SELECT COUNT(*) FROM journal_entries").fetchone()[0]
    token = ledger.set_acting_user("someone")
    try:
        body = "\n".join(text_of(specs.build(repo.conn, config)))
        assert ledger.current_user() == "someone"  # the sample user is undone
    finally:
        ledger.reset_acting_user(token)
    assert "REAL CLIENT OF MICRONET" not in body
    assert "SAMPLE LOCAL CLIENT, INC." in body
    assert repo.conn.execute("SELECT COUNT(*) FROM journal_entries").fetchone()[0] == before


def test_page_and_download(client, config):
    page = client.get("/books").get_data(as_text=True)
    assert "System and Technical Specifications (PDF)" in page and "data-sign" in page
    r = client.get("/books/system-specifications.pdf")
    assert r.status_code == 200 and r.mimetype == "application/pdf"
    conn = sqlite3.connect(config.db_path)
    assert conn.execute("SELECT COUNT(*) FROM audit_log WHERE action = 'print' "
                        "AND entity_id = 'system-specifications'").fetchone()[0] == 1


def test_sign_the_specifications(client):
    client.post("/signatures", data={"drawing": data_url(signature_picture())})
    r = client.get("/sign", query_string={"src": "/books/system-specifications.pdf",
                                          "title": "System and Technical Specifications"})
    token = r.location.rsplit("/", 1)[1]
    page = client.get(f"/sign/{token}").get_data(as_text=True)
    assert "Page 8 of" in page  # the certification page can be chosen
    r = client.post(f"/sign/{token}", data={
        "placements": '[{"page": 7, "x": 0.12, "y": 0.27, "w": 0.25}]', "caption": "1"})
    assert r.status_code == 302
    pages = text_of(client.get("/signed/1.pdf").data)
    assert "8. Certification" in pages[7] and "Test admin" in pages[7]
